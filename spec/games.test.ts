import { beforeAll, describe, expect, inject, it } from "vitest";

// Drives the backend over HTTP against the RUNNING app, the same way
// invariants.test.ts does (spec/global-setup.ts finds it) — this is what
// proves the contract holds for the deployed image, not just for whichever
// function happened to be called directly.
const baseUrl = inject("baseUrl");

// Pulls the session cookie Set-Cookie sends back, so later requests can
// prove "the same player" across calls — mirroring how a real browser would
// carry it.
function sessionCookie(res: Response): string {
  const setCookie = res.headers.get("set-cookie");
  if (!setCookie) throw new Error("no Set-Cookie header on the response");
  return setCookie.split(";")[0];
}

let cookie: string;

beforeAll(async () => {
  // Visiting any page mints the anonymous player identity — this is the
  // backend's "player/session creation" step, done server-side before any
  // game is played.
  const res = await fetch(new URL("/play/", baseUrl));
  expect(res.status).toBe(200);
  cookie = sessionCookie(res);
});

describe("anonymous player identity", () => {
  it("is generated by the server, not accepted from the client", async () => {
    const res = await fetch(new URL("/api/session", baseUrl), { headers: { cookie } });
    expect(res.status).toBe(200);
    const body = await res.json();
    expect(body.displayName).toMatch(/^Player [0-9A-F]{4}$/);
  });

  it("gives two different browsers two different identities", async () => {
    const a = await fetch(new URL("/api/session", baseUrl));
    const b = await fetch(new URL("/api/session", baseUrl));
    const [nameA, nameB] = await Promise.all([a.json(), b.json()]);
    expect(nameA.displayName).not.toBe(nameB.displayName);
  });
});

describe("submitting a game result", () => {
  it("persists a valid result and the leaderboard reflects it", async () => {
    const score = 40;
    const ticks = 60;

    const submit = await fetch(new URL("/api/games", baseUrl), {
      method: "POST",
      headers: { "content-type": "application/json", cookie },
      body: JSON.stringify({ score, ticks }),
    });
    expect(submit.status).toBe(201);
    const submitted = await submit.json();
    expect(submitted.ok).toBe(true);
    expect(submitted.game.score).toBe(score);

    const leaderboard = await fetch(new URL("/api/leaderboard", baseUrl));
    expect(leaderboard.status).toBe(200);
    const { entries } = await leaderboard.json();
    const mine = entries.find((entry: { gameId: number }) => entry.gameId === submitted.game.id);
    expect(mine, "the just-submitted game should appear in the leaderboard").toBeTruthy();
    expect(mine.score).toBe(score);
    expect(mine.displayName).toBe(submitted.game.displayName);
  });

  it("refuses a score that's impossible for the reported survival time", async () => {
    // One tick can never justify a huge score — see game/validate.ts.
    const submit = await fetch(new URL("/api/games", baseUrl), {
      method: "POST",
      headers: { "content-type": "application/json", cookie },
      body: JSON.stringify({ score: 999_990, ticks: 1 }),
    });
    expect(submit.status).toBe(400);
    const body = await submit.json();
    expect(body.ok).toBe(false);

    // And it must not have been persisted.
    const leaderboard = await fetch(new URL("/api/leaderboard", baseUrl));
    const { entries } = await leaderboard.json();
    expect(entries.some((entry: { score: number }) => entry.score === 999_990)).toBe(false);
  });

  it("refuses a malformed body", async () => {
    const submit = await fetch(new URL("/api/games", baseUrl), {
      method: "POST",
      headers: { "content-type": "application/json", cookie },
      body: JSON.stringify({ score: "a lot", ticks: 5 }),
    });
    expect(submit.status).toBe(400);
  });
});

describe("the leaderboard", () => {
  it("survives being fetched again — persistence, not an in-memory list", async () => {
    const first = await fetch(new URL("/api/leaderboard", baseUrl));
    const second = await fetch(new URL("/api/leaderboard", baseUrl));
    const [a, b] = await Promise.all([first.json(), second.json()]);
    expect(b.entries).toEqual(a.entries);
  });

  it("is also rendered on the page, not just the JSON API", async () => {
    const res = await fetch(new URL("/leaderboard/", baseUrl));
    expect(res.status).toBe(200);
    const html = await res.text();
    expect(html).toContain("Leaderboard");
  });
});
